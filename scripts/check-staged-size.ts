// Pre-commit check: block staged files larger than MAX_TOKENS (tokens ≈ bytes / 4).
// Run by .vite-hooks/pre-commit.

import { isBinary, readStaged, stagedFiles } from "./staged.ts";

const MAX_TOKENS = 5000;
const BYTES_PER_TOKEN = 4;
const MAX_BYTES = MAX_TOKENS * BYTES_PER_TOKEN;

// Files nobody writes by hand: lockfiles, build output, generated code.
const IGNORED_FILE_NAMES = [
  "package-lock.json",
  "npm-shrinkwrap.json",
  "yarn.lock",
  "pnpm-lock.yaml",
  "bun.lock",
  "bun.lockb",
  "Cargo.lock",
  "poetry.lock",
  "uv.lock",
  "go.sum",
];
const IGNORED_FOLDERS = ["node_modules", "dist", "build", "out", "coverage", "generated", "__generated__"];
const IGNORED_SUFFIXES = [
  ".lock",
  ".min.js",
  ".min.css",
  ".map",
  ".snap",
  ".generated.ts",
  ".gen.ts",
  ".d.ts",
];
const GENERATED_MARKERS = ["@generated", "DO NOT EDIT", "auto-generated", "autogenerated"];

function isIgnoredByPath(path: string): boolean {
  const segments = path.split("/");
  const name = segments[segments.length - 1];
  if (IGNORED_FILE_NAMES.includes(name)) {
    return true;
  }
  for (const folder of segments.slice(0, -1)) {
    if (IGNORED_FOLDERS.includes(folder)) {
      return true;
    }
  }
  for (const suffix of IGNORED_SUFFIXES) {
    if (name.endsWith(suffix)) {
      return true;
    }
  }
  return false;
}

/** Codegen tools announce themselves near the top of the file. */
function isGenerated(content: Buffer): boolean {
  const head = content.subarray(0, 1000).toString("utf8");
  for (const marker of GENERATED_MARKERS) {
    if (head.includes(marker)) {
      return true;
    }
  }
  return false;
}

interface Oversized {
  path: string;
  tokens: number;
}

function findOversized(): Oversized[] {
  const oversized: Oversized[] = [];
  for (const path of stagedFiles()) {
    if (isIgnoredByPath(path)) {
      continue;
    }
    const content = readStaged(path);
    if (content.length <= MAX_BYTES) {
      continue;
    }
    if (isBinary(content) || isGenerated(content)) {
      continue;
    }
    oversized.push({ path, tokens: Math.ceil(content.length / BYTES_PER_TOKEN) });
  }
  return oversized;
}

function printError(files: Oversized[]): void {
  const lines = [
    "",
    `✖ Commit blocked: ${files.length} staged file(s) exceed ${MAX_TOKENS} tokens (tokens = bytes / ${BYTES_PER_TOKEN}, limit ${MAX_BYTES} bytes).`,
    "",
  ];
  for (const file of files) {
    const overBy = file.tokens - MAX_TOKENS;
    lines.push(`   ${file.path}  ~${file.tokens} tokens (${overBy} over)`);
  }
  lines.push(
    "",
    "How to split an oversized file:",
    "  1. Find the seams: group the code by responsibility (types, pure helpers, I/O, one class each,",
    "     route handlers, CLI commands). Each group becomes its own file named after what it does,",
    "     e.g. store.ts → store-files.ts + store-users.ts, or vault.ts → vault.ts + vault-disk.ts.",
    "  2. Move whole units (functions, classes, constant tables) – don't cut a function in half.",
    "     Move shared types to a `*-types.ts` file so the new files don't import each other in a cycle.",
    "  3. Keep the public API stable: the original file can re-export what moved",
    '     (`export { thing } from "./thing.ts";`), or update the importers.',
    "  4. Tests: split by feature into separate *.test.ts files with a shared helpers file.",
    "  5. Aim for each new file well under the limit (≤ 4000 tokens) so it has room to grow.",
    "  6. Stage the new files too (`git add <new files>`) and commit again.",
    "",
    "  Do not minify, strip comments, or join lines to squeeze under the limit.",
    "  If the file really is generated or not hand-written, add its name/folder/suffix to the",
    "  ignore lists in scripts/check-staged-size.ts instead of using --no-verify.",
    "",
  );
  console.error(lines.join("\n"));
}

const oversized = findOversized();
if (oversized.length > 0) {
  printError(oversized);
  process.exit(1);
}
